"""Build the DPS Setup GUI (dps_gui.py) into a Windows exe with PyInstaller.

Usage:  python build_exe.py             -> dist\\DPS_Setup\\DPS_Setup.exe  + dist\\DPS_Setup.zip
        python build_exe.py --onefile   -> dist\\DPS_Setup.exe (single file, see note)

To use on another PC: copy DPS_Setup.zip, extract it, run DPS_Setup.exe. No Python needed,
but that PC needs the CH340 (CH341SER) driver for the DX-CP11 dongle.

Why a folder by default: on the Delta PCs Trend Micro Apex One quarantines the single-file
exe within ~15 s, and a single file also unpacks itself on every launch (~60 s to open
vs ~3 s for the folder build).
"""

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAME = 'DPS_Setup'
DIST = HERE / 'dist'
# Build outside OneDrive: sync locks files mid-build and makes rebuilds fail.
WORK = Path(tempfile.gettempdir()) / 'dps_setup_build'

# Bundled files the GUI never uses; dropping them halves the size.
STRIP = ['opengl32sw.dll', 'Qt6Network', 'Qt6Svg', 'Qt6Pdf', 'Qt6Qml', 'Qt6Quick',
         'translations', 'imageformats', 'iconengines', 'libcrypto', 'libssl', '_ssl', '_hashlib']

SPEC = '''# Generated by build_exe.py - edit that file instead.
strip = {strip!r}
keep = lambda entry: not any(s in entry[0] for s in strip)
a = Analysis([{script!r}], pathex=[{here!r}], excludes=['tkinter', 'ssl', 'PyQt6.QtNetwork', 'PyQt6.QtSvg'])
a.binaries = [b for b in a.binaries if keep(b)]
a.datas = [d for d in a.datas if keep(d)]
pyz = PYZ(a.pure)
if {onefile!r}:
    exe = EXE(pyz, a.scripts, a.binaries, a.datas, [], name={name!r}, console=False, upx=False)
else:
    exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name={name!r}, console=False, upx=False)
    coll = COLLECT(exe, a.binaries, a.datas, name={name!r}, upx=False)
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--onefile', action='store_true', help='single exe instead of a folder (see note above)')
    args = ap.parse_args()

    subprocess.run([sys.executable, '-m', 'pip', 'install', '--quiet',
                    'pyserial', 'pyqt6', 'pyinstaller'], check=True)
    shutil.rmtree(WORK, ignore_errors=True)
    WORK.mkdir(parents=True)
    spec = WORK / f'{NAME}.spec'
    spec.write_text(SPEC.format(strip=STRIP, script=str(HERE / 'dps_gui.py'), here=str(HERE),
                                onefile=args.onefile, name=NAME))
    subprocess.run([sys.executable, '-m', 'PyInstaller', '--noconfirm',
                    '--distpath', str(WORK / 'dist'), '--workpath', str(WORK / 'build'),
                    str(spec)], check=True, cwd=HERE)

    DIST.mkdir(exist_ok=True)
    if args.onefile:
        out = DIST / f'{NAME}.exe'
        shutil.copy2(WORK / 'dist' / f'{NAME}.exe', out)
    else:
        built = WORK / 'dist' / NAME
        shutil.rmtree(DIST / NAME, ignore_errors=True)
        shutil.copytree(built, DIST / NAME, dirs_exist_ok=True)
        shutil.make_archive(str(DIST / NAME), 'zip', built.parent, NAME)
        out = DIST / NAME / f'{NAME}.exe'
        print(f'Zip to share: {DIST / (NAME + ".zip")}')
    print(f'Built {out}')


if __name__ == '__main__':
    main()
